export function runGroupToString(runGroup: number, gender: Gender): string {
  const {
    fastest: [minRunMins, minRunSecs],
  } = gender === 'male' ? runMaleLimits : runFemaleLimits;

  const minDuration = minRunMins * 60 + minRunSecs;
  const totalSeconds = runGroup * 10 + minDuration;

  const mins = Math.floor(totalSeconds / 60).toString();
  const secs = (totalSeconds % 60).toString().padStart(2, '0');

  return `${mins}:${secs}`;
}

/**
 * Given an actual age value, return the age group (0-14)
 */
export function getAgeGroup(age: number): number {
  if (age >= 58) return 13;
  if (age < 22) return 0;

  return Math.floor((age - 22) / 3) + 1;
}

/**
 * Given the score table, age group and repetitions, returns the number
 * of points scored
 */
export function getScore(table: AgeGroupRange[], ageGroup: number, reps: number): number {
  if (reps >= table.length) {
    reps = table.length - 1;
  }

  return table[reps][ageGroup];
}

/**
 * Given the score table, age group and repetitions, returns how many more reps
 * are required to reach the next point. Returns `undefined` if max score
 * was already achieved.
 */
export function findNextPoint(
  table: AgeGroupRange[],
  ageGroup: number,
  reps: number,
  lowerIsBetter = false
): number | undefined {
  const currentScore = getScore(table, ageGroup, reps);
  if (lowerIsBetter) {
    for (let i = reps; i >= 0; i--) {
      const newScore = table[i][ageGroup];
      if (newScore > currentScore) return reps - i;
    }
  } else {
    for (let i = reps; i < table.length; i++) {
      const newScore = table[i][ageGroup];
      if (newScore > currentScore) return i - reps;
    }
  }

  return undefined;
}
