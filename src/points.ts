export interface RunLimits {
  fastest: [number, number];
  slowest: [number, number];
}

export const runMaleLimits: RunLimits = {
  fastest: [8, 20],
  slowest: [18, 20]
};

export const runFemaleLimits: RunLimits = {
  fastest: [10, 0],
  slowest: [21, 40]
};

export function getRunScore(
  runMinutes: number,
  runSeconds: number,
  ageGroup: number,
  gender: 'male' | 'female'
) {
  const {
    fastest: [minMins, minSecs],
    slowest: [maxMins, maxSecs]
  } = gender === 'male' ? runMaleLimits : runFemaleLimits;
  const table = gender === 'male' ? runMale : runFemale;

  if (runMinutes < minMins || (runMinutes === minMins && runSeconds < minSecs)) return 50;
  if (runMinutes > maxMins || (runMinutes === maxMins && runSeconds >= maxSecs)) return 0;

  const index = (runMinutes - minMins) * 6 + (runSeconds - minSecs) / 10;
  return table[index][ageGroup];
}

export function findNextRunPoint(
  runMinutes: number,
  runSeconds: number,
  ageGroup: number,
  gender: 'male' | 'female'
): number | undefined {
  const currentScore = getRunScore(runMinutes, runSeconds, ageGroup, gender);
  if (currentScore === 50) return undefined;

  const {
    fastest: [minMins, minSecs],
  } = gender === 'male' ? runMaleLimits : runFemaleLimits;

  const table = gender === 'male' ? runMale : runFemale;

  const timeIndex = (runMinutes - minMins) * 6 + (runSeconds - minSecs) / 10;
  let i = 0;
  while (i < timeIndex) {
    const newScore = table[timeIndex - i][ageGroup];
    if (newScore > currentScore) break;
    i++;
  }

  return i;
}

